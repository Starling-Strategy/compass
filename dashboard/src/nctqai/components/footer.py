def _link(label: str, href: str, external: bool):
    attrs = {"href": href, "cls": "dashboard-footer__link"}
    if external:
        attrs["target"] = "_blank"
        attrs["rel"] = "noopener noreferrer"
    return A(label, **attrs)


def _link_column(title: str, links):
    return Div(
        Span(title, cls="dashboard-footer__col-title"),
        *[_link(label, href, ext) for label, href, ext in links],
        cls="dashboard-footer__col",
    )


def Footer(year: str = ""):
    """Site footer with the NCTQ wordmark + two link columns.

    Rendered on every page via Layout(). The raw SVG is embedded as a NotStr
    CHILD of an FT element (a bare NotStr return doesn't render via to_xml in
    this FastHTML version).
    """
    copyright_line = f"© {year} NCTQ" if year else "© NCTQ"
    # The logo SVG is the full wordmark ("National Council on Teacher Quality"),
    # so no separate tagline text — that would duplicate the logo.
    brand = Div(
        Div(NotStr(_LOGO_SVG), cls="dashboard-footer__logo"),
        Span(copyright_line, cls="dashboard-footer__copyright"),
        cls="dashboard-footer__brand",
    )
    columns = Div(
        *[_link_column(title, links) for title, links in _FOOTER_LINK_COLUMNS],
        cls="dashboard-footer__links",
    )
    return FtFooter(
        Div(brand, columns, cls="dashboard-footer__inner"),
        *_google_analytics(),
        cls="dashboard-footer",
    )
